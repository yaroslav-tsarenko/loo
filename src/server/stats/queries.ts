import 'server-only'
import { and, desc, eq, gte, isNotNull, isNull, sql } from 'drizzle-orm'
import type { Conn } from '@/db/client'
import { readBatch } from '../db/batch'
import { attempts, chapterProgress, dailyActivity, examResults, lessonProgress, mistakes, sessions, srsCards, topicResults, units, xpLedger } from '@/db/schema'
import { dayKey, dayStartMs, DAY, shiftDay } from '@/progress/day'
import { STABLE_DAYS } from '@/progress/mastery'
import { HEAT_DAYS, SERIES_DAYS, SPEED_WINDOW_DAYS, type AttemptKind, type SpeedGroup, type SpeedWindow, type StatsAggregates, type TaskDifficulty } from '@/progress/stats'

// ts-fsrs State.Review
const REVIEW_STATE = 2
const QUIZ_MODES = new Set(['single', 'multi', 'output', 'order', 'fill'])
const DIFFICULTIES = new Set(['easy', 'medium', 'hard'])
// answers faster than this are mis-measured (double clicks, restored drafts)
const MIN_TIMED_MS = 500

const correctCount = sql<number>`count(*) filter (where ${attempts.correct})`
const timed = sql`${attempts.durationMs} >= ${MIN_TIMED_MS}`
const median = sql<number>`percentile_cont(0.5) within group (order by ${attempts.durationMs})`

// A day key as an SQL literal: the window expression appears in SELECT and GROUP BY, and bound parameters would make
// the two expressions differ ($1 vs $5). Day keys are generated by dayKey(), the pattern check keeps it that way.
function dayLiteral(day: string) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(day)) throw new Error('Bad day key')
  return sql.raw(`'${day}'`)
}

function speedWindow(today: string) {
  const recentFrom = shiftDay(today, -SPEED_WINDOW_DAYS)
  return sql<SpeedWindow>`case when ${attempts.day} = ${dayLiteral(today)} then 'today' when ${attempts.day} >= ${dayLiteral(recentFrom)} then 'recent' else 'previous' end`
}

// Every aggregate the statistics engine needs, in one user scope: per-kind/level/topic counts, speed medians, FSRS
// memory, results and records. All grouped in SQL (no per-item queries); cached per request (profile + coach).
export async function loadAggregates(db: Conn, userId: string, now: number): Promise<StatsAggregates> {
  const today = dayKey(now)
  const heatFrom = shiftDay(today, -(HEAT_DAYS - 1))
  const speedFrom = shiftDay(today, -SPEED_WINDOW_DAYS * 2)
  const seriesFrom = shiftDay(today, -(SERIES_DAYS - 1))
  const dayEnd = dayStartMs(now) + DAY
  const win = speedWindow(today)

  const runs = db
    .select({ correct: attempts.correct, grp: sql<number>`sum(case when ${attempts.correct} then 0 else 1 end) over (order by ${attempts.id})`.as('grp') })
    .from(attempts)
    .where(eq(attempts.userId, userId))
    .as('runs')

  // all nineteen in ONE statement (src/server/db/batch.ts)
  const [days, goalRows, kinds, levels, speedRows, speedDaily, topicRows, openRows, taskRows, memoryRows, testsRows, examsRows, lessonsRows, bestXpRows, bestAnswersRows, comboRows, fastestRows, readingRows, xpRows] = await readBatch(db, [
    db
      .select()
      .from(dailyActivity)
      .where(and(eq(dailyActivity.userId, userId), gte(dailyActivity.day, heatFrom))),
    db
      .select({ day: dailyActivity.day })
      .from(dailyActivity)
      .where(and(eq(dailyActivity.userId, userId), eq(dailyActivity.goalMet, true))),
    db.select({ kind: attempts.kind, total: sql<number>`count(*)`, correct: correctCount, ms: sql<number>`coalesce(sum(${attempts.durationMs}), 0)` }).from(attempts).where(eq(attempts.userId, userId)).groupBy(attempts.kind),
    db
      .select({ level: attempts.level, total: sql<number>`count(*)`, correct: correctCount, solved: sql<number>`count(distinct ${attempts.unitId}) filter (where ${attempts.correct})` })
      .from(attempts)
      .where(eq(attempts.userId, userId))
      .groupBy(attempts.level),
    // per kind (rolled up) and per kind + quiz mode, for today / recent 14 days / previous 14 days
    db
      .select({ kind: attempts.kind, qtype: units.qtype, rolled: sql<number>`grouping(${units.qtype})`, window: win, medianMs: median, n: sql<number>`count(*)` })
      .from(attempts)
      .leftJoin(units, eq(units.id, attempts.unitId))
      .where(and(eq(attempts.userId, userId), gte(attempts.day, speedFrom), timed))
      .groupBy(sql`grouping sets ((${attempts.kind}, ${units.qtype}, ${win}), (${attempts.kind}, ${win}))`),
    db
      .select({ day: attempts.day, medianMs: median, n: sql<number>`count(*)` })
      .from(attempts)
      .where(and(eq(attempts.userId, userId), eq(attempts.kind, 'quiz'), gte(attempts.day, seriesFrom), timed))
      .groupBy(attempts.day),
    db.select({ chapterId: attempts.chapterId, total: sql<number>`count(*)`, correct: correctCount }).from(attempts).where(eq(attempts.userId, userId)).groupBy(attempts.chapterId),
    db
      .select({ chapterId: units.chapterId, open: sql<number>`count(*)` })
      .from(mistakes)
      .innerJoin(units, eq(units.id, mistakes.unitId))
      .where(and(eq(mistakes.userId, userId), isNull(mistakes.resolvedAt)))
      .groupBy(units.chapterId),
    db
      .select({
        unitId: attempts.unitId,
        difficulty: sql<string | null>`max(${units.qtype})`,
        solved: sql<boolean>`bool_or(${attempts.outcome} = 'solved')`,
        firstTry: sql<boolean>`(array_agg(${attempts.outcome} order by ${attempts.id}))[1] = 'solved'`,
      })
      .from(attempts)
      .leftJoin(units, eq(units.id, attempts.unitId))
      .where(and(eq(attempts.userId, userId), eq(attempts.kind, 'task')))
      .groupBy(attempts.unitId),
    db
      .select({
        cards: sql<number>`count(*)`,
        reviewing: sql<number>`count(*) filter (where ${srsCards.state} = ${REVIEW_STATE})`,
        longTerm: sql<number>`count(*) filter (where ${srsCards.state} = ${REVIEW_STATE} and ${srsCards.stability} >= ${STABLE_DAYS})`,
        dueToday: sql<number>`count(*) filter (where ${srsCards.due} < ${dayEnd})`,
        lapses: sql<number>`coalesce(sum(${srsCards.lapses}), 0)`,
      })
      .from(srsCards)
      .where(eq(srsCards.userId, userId)),
    db
      .select({ passed: sql<number>`count(*) filter (where ${topicResults.passedAt} is not null)`, perfect: sql<number>`count(*) filter (where ${topicResults.bestScore} >= 1)` })
      .from(topicResults)
      .where(eq(topicResults.userId, userId)),
    db
      .select({ passed: sql<number>`count(*) filter (where ${examResults.passedAt} is not null)`, out: sql<number>`count(*) filter (where ${examResults.testOut})` })
      .from(examResults)
      .where(eq(examResults.userId, userId)),
    db
      .select({
        done: sql<number>`count(*) filter (where ${lessonProgress.completions} > 0)`,
        perfect: sql<number>`count(*) filter (where ${lessonProgress.bestAccuracy} >= 1)`,
        lastNew: sql<number | null>`max(${lessonProgress.firstCompletedAt})`,
      })
      .from(lessonProgress)
      .where(eq(lessonProgress.userId, userId)),
    db
      .select({ day: dailyActivity.day, value: dailyActivity.xp })
      .from(dailyActivity)
      .where(and(eq(dailyActivity.userId, userId), sql`${dailyActivity.xp} > 0`))
      .orderBy(desc(dailyActivity.xp), desc(dailyActivity.day))
      .limit(1),
    db
      .select({ day: dailyActivity.day, value: dailyActivity.total })
      .from(dailyActivity)
      .where(and(eq(dailyActivity.userId, userId), sql`${dailyActivity.total} > 0`))
      .orderBy(desc(dailyActivity.total), desc(dailyActivity.day))
      .limit(1),
    // gaps and islands: every wrong answer starts a new group; the longest group of correct answers is the combo
    db
      .select({ best: sql<number>`coalesce(max(n), 0)` })
      .from(
        db
          .select({ n: sql<number>`count(*) filter (where ${runs.correct})`.as('n') })
          .from(runs)
          .groupBy(runs.grp)
          .as('islands'),
      ),
    db
      .select({ ms: sql<number | null>`min(${sessions.endedAt} - ${sessions.startedAt})` })
      .from(sessions)
      .where(and(eq(sessions.userId, userId), eq(sessions.mode, 'lesson'), isNotNull(sessions.endedAt), sql`${sessions.total} >= 3`, sql`${sessions.correct} = ${sessions.total}`)),
    db.select({ ms: sql<number>`coalesce(sum(${chapterProgress.timeMs}), 0)` }).from(chapterProgress).where(eq(chapterProgress.userId, userId)),
    db.select({ total: sql<number>`coalesce(sum(${xpLedger.amount}), 0)` }).from(xpLedger).where(eq(xpLedger.userId, userId)),
  ])
  const [memory, tests, exams, lessons, bestXp, bestAnswers, combo, fastest, reading, xp] = [memoryRows[0], testsRows[0], examsRows[0], lessonsRows[0], bestXpRows[0], bestAnswersRows[0], comboRows[0], fastestRows[0], readingRows[0], xpRows[0]]

  const open = new Map(openRows.map((r) => [r.chapterId, Number(r.open)]))
  const topics = topicRows.map((r) => ({ chapterId: r.chapterId, total: Number(r.total), correct: Number(r.correct), open: open.get(r.chapterId) ?? 0 }))
  for (const [chapterId, n] of open) if (!topics.some((t) => t.chapterId === chapterId)) topics.push({ chapterId, total: 0, correct: 0, open: n })

  const speed: StatsAggregates['speed'] = []
  for (const r of speedRows) {
    const rolled = Number(r.rolled) === 1
    let group: SpeedGroup | null = null
    if (rolled) group = r.kind
    else if (r.kind === 'quiz' && r.qtype && QUIZ_MODES.has(r.qtype)) group = `quiz:${r.qtype}` as SpeedGroup
    if (group) speed.push({ group, window: r.window, medianMs: Math.round(Number(r.medianMs)), n: Number(r.n) })
  }

  return {
    today,
    xp: Number(xp?.total ?? 0),
    days: days.map((d) => ({ day: d.day, total: d.total, correct: d.correct, cards: d.cards, quizzes: d.quizzes, tasks: d.tasks, xp: d.xp, timeMs: d.timeMs, goalMet: d.goalMet })),
    goalDays: goalRows.map((r) => r.day),
    kinds: kinds.map((k) => ({ kind: k.kind as AttemptKind, total: Number(k.total), correct: Number(k.correct), ms: Number(k.ms) })),
    levels: levels.map((l) => ({ level: l.level, total: Number(l.total), correct: Number(l.correct), solved: Number(l.solved) })),
    speed,
    speedDaily: speedDaily.map((r) => ({ day: r.day, medianMs: Math.round(Number(r.medianMs)), n: Number(r.n) })),
    topics,
    tasks: taskRows.map((t) => ({ unitId: t.unitId, difficulty: t.difficulty && DIFFICULTIES.has(t.difficulty) ? (t.difficulty as TaskDifficulty) : null, solved: Boolean(t.solved), firstTry: Boolean(t.firstTry) })),
    memory: {
      cards: Number(memory?.cards ?? 0),
      reviewing: Number(memory?.reviewing ?? 0),
      longTerm: Number(memory?.longTerm ?? 0),
      dueToday: Number(memory?.dueToday ?? 0),
      lapses: Number(memory?.lapses ?? 0),
    },
    results: {
      testsPassed: Number(tests?.passed ?? 0),
      testsPerfect: Number(tests?.perfect ?? 0),
      examsPassed: Number(exams?.passed ?? 0),
      testedOut: Number(exams?.out ?? 0),
      lessonsDone: Number(lessons?.done ?? 0),
      perfectLessons: Number(lessons?.perfect ?? 0),
      lastNewLessonAt: lessons?.lastNew === null || lessons?.lastNew === undefined ? null : Number(lessons.lastNew),
    },
    records: {
      bestDayXp: bestXp ? { day: bestXp.day, value: bestXp.value } : null,
      bestDayAnswers: bestAnswers ? { day: bestAnswers.day, value: bestAnswers.value } : null,
      longestCombo: Number(combo?.best ?? 0),
      fastestPerfectLessonMs: fastest?.ms === null || fastest?.ms === undefined ? null : Number(fastest.ms),
    },
    readingMs: Number(reading?.ms ?? 0),
  }
}
