// One emoji grapheme: flag pairs, or a pictograph with optional VS16 / skin tone / ZWJ sequence.
export const EMOJI_RE = /\p{Regional_Indicator}{2}|\p{Extended_Pictographic}️?(?:\p{Emoji_Modifier})?(?:‍\p{Extended_Pictographic}️?)*/gu

export function emojiIcon(emoji: string): PixelIconName | null {
  return EMOJI_ICON[emoji.replace(/️/g, '')] ?? null
}
