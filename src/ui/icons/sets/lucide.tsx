export type LucideName = keyof typeof LUCIDE

export default function LucideGlyph({ name, size, className }: GlyphProps) {
  const Glyph = (LUCIDE as Record<string, LucideIcon>)[name]
  if (!Glyph) return null
  return <Glyph size={size} strokeWidth={2.2} className={className} aria-hidden="true" focusable="false" />
}
