export type SiName = keyof typeof SI

export default function SiGlyph({ name, size, mono, className }: GlyphProps) {
  const entry = (SI as Record<string, Brand>)[name]
  if (!entry) return null
  const Glyph = entry.icon
  return <Glyph size={size} color={mono ? 'currentColor' : brandFill(entry.hex)} className={className} aria-hidden="true" focusable="false" />
}
