import postgres from 'postgres'

// Copies all progress from one Postgres to another (e.g. local PGlite → Supabase) table by table.
// Usage: SOURCE_URL=postgres://postgres@127.0.0.1:54329/postgres pnpm db:copy   (target = DIRECT_URL)
// Refuses to overwrite a target that already has attempts unless --force is passed.
const sourceUrl = process.env.SOURCE_URL ?? 'postgres://postgres@127.0.0.1:54329/postgres'
const targetUrl = process.env.DIRECT_URL ?? process.env.DATABASE_URL
if (!targetUrl) throw new Error('DIRECT_URL / DATABASE_URL (ціль) не задано')
if (targetUrl === sourceUrl) throw new Error('Джерело і ціль однакові')

// FK order: profiles before per-user tables, news_items before news_reads. Both databases must be on the same
// migration (pnpm db:migrate). Supabase: profiles of real users only exist after they signed in there; copying the
// legacy owner (00000000-…) is what you want — the admin claims it on first sign-in.
const TABLES = [
  'profiles', 'system_state', 'user_settings', 'units', 'unit_aliases', 'sessions', 'attempts', 'srs_cards', 'mistakes', 'chapter_progress',
  'task_state', 'xp_ledger', 'achievements', 'daily_activity', 'daily_missions', 'reel_state', 'lesson_progress', 'news_items', 'news_reads',
  'generated_reels',
]

const src = postgres(sourceUrl, { max: 1, prepare: false, onnotice: () => {} })
const dst = postgres(targetUrl, { max: 1, prepare: false, onnotice: () => {} })

const [row] = await dst`select count(*)::int as n from attempts`
const n = Number(row?.n ?? 0)
if (n > 0 && !process.argv.includes('--force')) {
  console.error(`У цілі вже є ${n} спроб — копіювання скасовано (додай --force, щоб замінити дані)`)
  process.exit(1)
}

// Which columns are jsonb: their values must be sent as JSON even when they're scalars.
const jsonCols = new Set(
  (await dst`select table_name, column_name from information_schema.columns where table_schema = 'public' and data_type = 'jsonb'`).map((r) => `${r.table_name}.${r.column_name}`),
)

await dst.begin(async (tx) => {
  for (const table of [...TABLES].reverse()) await tx`delete from ${tx(table)}`
  for (const table of TABLES) {
    const rows = await src`select * from ${src(table)}`
    for (let i = 0; i < rows.length; i += 500) {
      const chunk = rows.slice(i, i + 500).map((row) =>
        Object.fromEntries(Object.entries(row).map(([k, v]) => [k, v !== null && jsonCols.has(`${table}.${k}`) ? tx.json(v as never) : v])),
      )
      // Identity columns are GENERATED BY DEFAULT, so explicit ids from the source are kept as is.
      await tx`insert into ${tx(table)} ${tx(chunk)}`
    }
    console.log(`  ${table}: ${rows.length}`)
  }
  for (const table of ['attempts', 'xp_ledger']) {
    await tx.unsafe(`select setval(pg_get_serial_sequence('${table}', 'id'), coalesce((select max(id) from ${table}), 0) + 1, false)`)
  }
})
console.log('✅ Прогрес скопійовано')
await src.end()
await dst.end()
