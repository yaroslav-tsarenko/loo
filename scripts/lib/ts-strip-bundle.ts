import { build, type Plugin } from 'esbuild'
import { fileURLToPath } from 'node:url'

// Bundles src/ui/code/ts-strip.ts (sucrase, typescript transform only) into one self-contained expression
// that evaluates to prepareTypeScript — inlined into the /runner/worker.js source, so the worker keeps its
// CSP (no importScripts, no network) and sucrase never reaches a page bundle.

const ROOT = fileURLToPath(new URL('../../', import.meta.url))
export const ENTRY = 'src/ui/code/ts-strip.ts'
export const OUTPUT = 'src/ui/code/ts-strip.bundle.generated.ts'

// transform() validates options with ts-interface-checker and can emit source maps (@jridgewell/*);
// we pass fixed options and never ask for maps, so both are stubbed out (~23 KB minified less).
const slim: Plugin = {
  name: 'sucrase-slim',
  setup(b) {
    b.onResolve({ filter: /^\.\/(Options|computeSourceMap)$/ }, (a) => (/sucrase[\\/]dist[\\/]esm[\\/]index\.js$/.test(a.importer) ? { path: a.path, namespace: 'sucrase-slim' } : undefined))
    b.onLoad({ filter: /.*/, namespace: 'sucrase-slim' }, (a) => ({
      loader: 'js',
      contents: a.path.endsWith('Options') ? 'export function validateOptions() {}' : 'export default function computeSourceMap() { throw new Error("source maps are disabled") }',
    }))
  },
}

export async function bundleTsStrip(): Promise<string> {
  const result = await build({
    absWorkingDir: ROOT,
    entryPoints: [ENTRY],
    bundle: true,
    minify: true,
    format: 'iife',
    globalName: '__tsStrip',
    platform: 'browser',
    target: 'es2022',
    legalComments: 'none',
    write: false,
    plugins: [slim],
  })
  const code = result.outputFiles[0]!.text.trim()
  return `(function () {\n${code}\nreturn __tsStrip.prepareTypeScript\n})()`
}

export function generatedModule(expression: string, version: string): string {
  return `// GENERATED by \`pnpm runner:build\` (scripts/build-ts-strip.ts) from ${ENTRY} + sucrase@${version}. Do not edit.
// An expression that evaluates to prepareTypeScript(code, tests); inlined into the runner worker source.
export const TS_STRIP_SUCRASE_VERSION = ${JSON.stringify(version)}
export const TS_STRIP_SOURCE = ${JSON.stringify(expression)}
`
}
