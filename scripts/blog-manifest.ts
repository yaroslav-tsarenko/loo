// Writes src/blog/manifest.generated.ts — the slugs of blog/uk/*.md — so the proxy can answer 404 for unknown
// /blog/<slug> without touching the disk (src/proxy.ts → blogPathExists). vercel-build runs it before `next build`;
// tests/unit/blog.test.ts fails when the committed copy is stale.
import { readdir, writeFile } from 'node:fs/promises'

export async function blogSlugs(): Promise<string[]> {
  return (await readdir('blog/uk').catch(() => [] as string[]))
    .filter((f) => f.endsWith('.md'))
    .map((f) => f.slice(0, -3))
    .sort()
}

export function manifestSource(slugs: readonly string[]): string {
  return `// Generated by scripts/blog-manifest.ts (pnpm blog:manifest) — do not edit.\nexport const BLOG_SLUGS: readonly string[] = ${JSON.stringify(slugs, null, 2)}\n`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const slugs = await blogSlugs()
  await writeFile('src/blog/manifest.generated.ts', manifestSource(slugs))
  console.log(`blog manifest: ${slugs.length} posts`)
}
