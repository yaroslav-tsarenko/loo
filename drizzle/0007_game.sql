-- ── Supabase only: per-request RLS for the `authenticated` role (same pattern as 0005) ────────────────────────
-- league_cohorts gets no grant and no policy: cohorts, leaderboards and week finalization run as the server (owner)
-- outside any user transaction, and only display names / avatars / weekly XP ever leave it.
DO $$
DECLARE t text;
BEGIN
  IF to_regnamespace('auth') IS NULL
     OR NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated')
     OR to_regprocedure('auth.uid()') IS NULL THEN
    RAISE NOTICE 'No Supabase auth schema: RLS policies skipped (local PGlite / plain Postgres)';
    RETURN;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON public.league_cohorts FROM anon;
  END IF;
  REVOKE ALL ON public.league_cohorts FROM authenticated;
  FOREACH t IN ARRAY ARRAY['user_state', 'gem_ledger', 'inventory', 'frozen_days', 'league_members'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
      EXECUTE format('REVOKE ALL ON public.%I FROM anon', t);
    END IF;
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON public.%I TO authenticated', t);
    EXECUTE format('DROP POLICY IF EXISTS own_rows ON public.%I', t);
    EXECUTE format('CREATE POLICY own_rows ON public.%I FOR ALL TO authenticated USING (user_id = (SELECT auth.uid())) WITH CHECK (user_id = (SELECT auth.uid()))', t);
  END LOOP;
  -- The ledger is append-only for users: no UPDATE / DELETE of past entries.
  REVOKE UPDATE, DELETE ON public.gem_ledger FROM authenticated;
  GRANT USAGE, SELECT ON SEQUENCE public.gem_ledger_id_seq TO authenticated;
END $$;
