-- RPG layer (docs/ECONOMY.md): two currencies, gear, «шлях воїна».
-- * buck_ledger: append-only bucks (the everyday currency), same shape and rules as gem_ledger — unique
--   (user_id, reason, ref_id) so each award lands once; users may only read / insert their own rows.
-- * user_state.gear: equipped gear (item id per slot: head, body, weapon, amulet, aura); owned gear lives in inventory.
-- * user_state.evo_step / evo_seen: the character rank moves from Loo's 22 evolution steps (0–21) to the 56 steps of
--   «шлях воїна» (0–55), mapped proportionally (round(step · 55 / 21)) and kept as already announced. The next settle
--   raises the step to whatever XP + course milestones give (never lowers it); new steps pay gems under `rank:<n>` refs,
--   so old `evo:<n>` awards never collide.
-- * Supabase only (guarded like 0005/0007, so this also runs on PGlite): RLS `user_id = auth.uid()` + grants.

CREATE TABLE "buck_ledger" (
	"id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (sequence name "buck_ledger_id_seq" INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CACHE 1),
	"user_id" uuid NOT NULL,
	"amount" integer NOT NULL,
	"reason" text NOT NULL,
	"ref_id" text NOT NULL,
	"created_at" bigint NOT NULL,
	"day" text NOT NULL
);
