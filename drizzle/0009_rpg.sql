-- ── Supabase only: per-request RLS for the `authenticated` role (same pattern as 0007's gem_ledger) ─────────────
DO $$
BEGIN
  IF to_regnamespace('auth') IS NULL
     OR NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated')
     OR to_regprocedure('auth.uid()') IS NULL THEN
    RAISE NOTICE 'No Supabase auth schema: RLS policies skipped (local PGlite / plain Postgres)';
    RETURN;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON public.buck_ledger FROM anon;
  END IF;
  GRANT SELECT, INSERT ON public.buck_ledger TO authenticated;
  DROP POLICY IF EXISTS own_rows ON public.buck_ledger;
  CREATE POLICY own_rows ON public.buck_ledger FOR ALL TO authenticated USING (user_id = (SELECT auth.uid())) WITH CHECK (user_id = (SELECT auth.uid()));
  -- The ledger is append-only for users: no UPDATE / DELETE of past entries.
  REVOKE UPDATE, DELETE ON public.buck_ledger FROM authenticated;
  GRANT USAGE, SELECT ON SEQUENCE public.buck_ledger_id_seq TO authenticated;
END $$;
